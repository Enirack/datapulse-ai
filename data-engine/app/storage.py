import os
import uuid


class StorageError(Exception):
    """A storage identifier didn't resolve to a real file inside the storage root."""


class DatasetStorageResolver:
    """
    Resolves an opaque storage identifier (as generated by the backend's
    LocalFilesystemDatasetStorage — `{2-char shard}/{uuid}.{ext}`) to an
    absolute path, refusing to look outside the configured storage root.

    This service never receives a filename from an end user, only an
    identifier the backend generated itself — but resolution is still
    verified defensively (path containment + symlink rejection), mirroring
    the same checks the PHP-side storage class applies.
    """

    def __init__(self, root_dir: str) -> None:
        self.root_dir = os.path.realpath(root_dir)

    def resolve(self, storage_identifier: str) -> str:
        if not storage_identifier or "\x00" in storage_identifier or ".." in storage_identifier:
            raise StorageError("Invalid storage identifier.")

        candidate = os.path.join(self.root_dir, storage_identifier)

        if os.path.islink(candidate):
            raise StorageError("Stored file not found.")

        real = os.path.realpath(candidate)
        if real != self.root_dir and not real.startswith(self.root_dir + os.sep):
            raise StorageError("Invalid storage identifier.")

        if not os.path.isfile(real):
            raise StorageError("Stored file not found.")

        return real


class TempStorageWriter:
    """
    Writes a cleaning result into the shared tmp handoff area, using the
    same `{2-char shard}/{uuid}.{ext}` identifier shape the backend's own
    storage class uses for permanent files — never re-using or deriving
    the identifier from anything user-supplied.

    The backend is responsible for moving (committing) this file into
    permanent storage; this class only ever writes under `root_dir`, never
    under the (read-mostly, from here) dataset storage root.
    """

    def __init__(self, root_dir: str) -> None:
        self.root_dir = root_dir

    def write(self, content: bytes, extension: str) -> str:
        """Returns the identifier (relative to root_dir) of the written file."""
        file_uuid = str(uuid.uuid4())
        shard = file_uuid[:2]
        shard_dir = os.path.join(self.root_dir, shard)
        os.makedirs(shard_dir, exist_ok=True)

        identifier = f"{shard}/{file_uuid}.{extension}"
        path = os.path.join(self.root_dir, identifier)

        with open(path, "wb") as handle:
            handle.write(content)

        return identifier
